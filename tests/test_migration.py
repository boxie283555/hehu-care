import os
import sqlite3
import tempfile
from pathlib import Path
from unittest import TestCase
from unittest.mock import patch
import database
from tools.test_database import create,drop
from tools.migrate_sqlite import migrate,TABLES

class MigrationTests(TestCase):
    def test_import_preserves_ids_unicode_and_next_sequence(self):
        name=create()
        with tempfile.TemporaryDirectory() as tmp,patch.dict(os.environ,{'HEHU_DB_SCHEMA':name}):
            database.close_pool()
            try:
                # Recreate the previous SQLite table contract for all business tables.
                source=Path(tmp)/'old.sqlite3'
                with sqlite3.connect(source) as src:
                    schema=(database.ROOT/'sql/001_initial.sql').read_text()
                    import re
                    for statement in schema.split(';'):
                        match=re.search(r'CREATE TABLE IF NOT EXISTS (\w+)',statement)
                        if match and match[1] in TABLES:
                            src.execute(statement.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY','INTEGER PRIMARY KEY').replace('BIGINT','INTEGER').replace('DOUBLE PRECISION','REAL'))
                    src.execute("INSERT INTO users(id,phone,name,role) VALUES(42,'13900000000','迁移家长','guardian')")
                    src.execute("INSERT INTO children(id,owner,name,sex,birth,allergies,feeding,history,created) VALUES(71,42,'迁移宝宝','女','2025-01-01','不清楚','普通膳食','无','2026-11-03')")
                original=source.read_bytes()
                self.assertEqual(migrate(source)['users'],1)
                self.assertEqual(migrate(source,True)['children'],1)
                with database.connect() as conn:
                    self.assertEqual(conn.execute('SELECT name FROM children WHERE id=71').fetchone()['name'],'迁移宝宝')
                    new=conn.execute("INSERT INTO users(phone,name,role) VALUES('13888888888','新家长','guardian') RETURNING id").fetchone()['id']
                    self.assertGreater(new,42)
                with self.assertRaises(ValueError):migrate(source,True)
                self.assertEqual(source.read_bytes(),original)
                self.assertTrue(list((Path(tmp)/'backups').glob('*.sqlite3')))
            finally:database.close_pool();drop(name)
